import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { imageBase64 } = await req.json();
    
    if (!imageBase64) {
      return new Response(
        JSON.stringify({ error: 'Image is required' }),
        { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const LOVABLE_API_KEY = Deno.env.get('LOVABLE_API_KEY');
    if (!LOVABLE_API_KEY) {
      throw new Error('LOVABLE_API_KEY is not configured');
    }

    console.log('Processing watermark removal...');

    const prompt = `Remove any watermarks, text overlays, or logos from this image. Keep the main subject and background intact. Only remove visible watermarks, stamps, or text overlays. Provide a clean version of the image without any watermarks.`;

    console.log('Calling Lovable AI (Nano Banana) for watermark removal...');
    
    const response = await fetch('https://ai.gateway.lovable.dev/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${LOVABLE_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'google/gemini-2.5-flash-image-preview',
        messages: [
          {
            role: 'user',
            content: [
              {
                type: 'text',
                text: prompt
              },
              {
                type: 'image_url',
                image_url: {
                  url: imageBase64
                }
              }
            ]
          }
        ],
        modalities: ['image', 'text']
      })
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('Lovable AI error:', response.status, errorText);
      
      if (response.status === 429) {
        throw new Error('Rate limit exceeded. Please try again in a moment.');
      }
      if (response.status === 402) {
        throw new Error('AI credits exhausted. Please add credits to continue.');
      }
      
      throw new Error(`AI service error: ${response.status} - ${errorText}`);
    }

    const result = await response.json();
    console.log('Lovable AI response received');

    // Extract the generated image from the response
    let cleanImageUrl: string | undefined = result?.choices?.[0]?.message?.images?.[0]?.image_url?.url;

    // Fallback: some responses embed images inside message.content as parts
    if (!cleanImageUrl) {
      const content = result?.choices?.[0]?.message?.content;
      if (Array.isArray(content)) {
        const imagePart = content.find((p: any) => p?.type === 'image_url' && p?.image_url?.url);
        cleanImageUrl = imagePart?.image_url?.url;
      }
    }

    // Fallback: direct image_url on message
    if (!cleanImageUrl) {
      const maybe = result?.choices?.[0]?.message?.image_url?.url;
      if (typeof maybe === 'string') cleanImageUrl = maybe;
    }

    if (cleanImageUrl) {
      return new Response(
        JSON.stringify({ 
          success: true, 
          cleanImage: cleanImageUrl,
          message: 'Watermark removed successfully'
        }),
        { 
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
          status: 200 
        }
      );
    }

    console.error('No image data found in AI response:', JSON.stringify(result));
    throw new Error('No image generated by AI');

  } catch (error) {
    console.error('Error in remove-watermark function:', error);
    return new Response(
      JSON.stringify({ 
        error: error instanceof Error ? error.message : 'Unknown error occurred',
        details: 'Failed to process image with AI'
      }),
      { 
        status: 500, 
        headers: { ...corsHeaders, 'Content-Type': 'application/json' } 
      }
    );
  }
});
