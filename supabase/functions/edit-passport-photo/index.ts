import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { imageBase64, instructions, photoSize } = await req.json();
    
    if (!imageBase64 || !instructions) {
      return new Response(
        JSON.stringify({ error: 'Image and instructions are required' }),
        { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const GEMINI_API_KEY = Deno.env.get('GEMINI_API_KEY');
    if (!GEMINI_API_KEY) {
      throw new Error('GEMINI_API_KEY is not configured');
    }

    console.log('Processing image edit request for size:', photoSize);
    
    // Extract base64 data without the data URL prefix
    const base64Data = imageBase64.split(',')[1] || imageBase64;

    // Create the prompt for Nano Banana
    const prompt = `Create a professional passport photo with these requirements: ${instructions}. 
    Make sure the photo has:
    - Professional lighting and quality
    - Plain, neutral background (preferably white or light blue)
    - Person centered and facing forward
    - Clear facial features
    - Appropriate framing for ${photoSize} passport photo
    - High quality and sharp details
    Maintain the person's appearance but optimize for official document standards.`;

    const requestBody = {
      contents: [{
        parts: [
          {
            text: prompt
          },
          {
            inline_data: {
              mime_type: "image/jpeg",
              data: base64Data
            }
          }
        ]
      }],
      generationConfig: {
        temperature: 0.4,
        topK: 32,
        topP: 1,
        maxOutputTokens: 4096,
      }
    };

    console.log('Calling Gemini API for image editing...');
    
    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash-exp:generateContent?key=${GEMINI_API_KEY}`,
      {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify(requestBody)
      }
    );

    if (!response.ok) {
      const errorText = await response.text();
      console.error('Gemini API error:', response.status, errorText);
      throw new Error(`Gemini API error: ${response.status} - ${errorText}`);
    }

    const result = await response.json();
    console.log('Gemini API response received');

    // Extract the generated image from the response
    if (result.candidates && result.candidates[0]?.content?.parts) {
      const parts = result.candidates[0].content.parts;
      
      // Look for inline_data in the response
      for (const part of parts) {
        if (part.inline_data && part.inline_data.data) {
          const editedImageBase64 = `data:${part.inline_data.mime_type};base64,${part.inline_data.data}`;
          
          return new Response(
            JSON.stringify({ 
              success: true, 
              editedImage: editedImageBase64,
              message: 'Photo edited successfully'
            }),
            { 
              headers: { ...corsHeaders, 'Content-Type': 'application/json' },
              status: 200 
            }
          );
        }
      }
    }

    // If no image found in response, return error
    console.error('No image data found in Gemini response:', JSON.stringify(result));
    throw new Error('No image generated by AI');

  } catch (error) {
    console.error('Error in edit-passport-photo function:', error);
    return new Response(
      JSON.stringify({ 
        error: error instanceof Error ? error.message : 'Unknown error occurred',
        details: 'Failed to process image with AI'
      }),
      { 
        status: 500, 
        headers: { ...corsHeaders, 'Content-Type': 'application/json' } 
      }
    );
  }
});
