import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { imageBase64, instructions, photoSize } = await req.json();
    
    if (!imageBase64 || !instructions) {
      return new Response(
        JSON.stringify({ error: 'Image and instructions are required' }),
        { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      );
    }

    const LOVABLE_API_KEY = Deno.env.get('LOVABLE_API_KEY');
    if (!LOVABLE_API_KEY) {
      throw new Error('LOVABLE_API_KEY is not configured');
    }

    console.log('Processing image edit request for size:', photoSize);

    // Create the prompt for Nano Banana
    const prompt = `Create a professional passport photo with these requirements: ${instructions}. 
    Make sure the photo has:
    - Professional lighting and quality
    - Plain, neutral background (preferably white or light blue)
    - Person centered and facing forward
    - Clear facial features
    - Appropriate framing for ${photoSize} passport photo
    - High quality and sharp details
    Maintain the person's appearance but optimize for official document standards.`;

    console.log('Calling Lovable AI (Nano Banana) for image editing...');
    
    const response = await fetch('https://ai.gateway.lovable.dev/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${LOVABLE_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'google/gemini-2.5-flash-image-preview',
        messages: [
          {
            role: 'user',
            content: [
              {
                type: 'text',
                text: prompt
              },
              {
                type: 'image_url',
                image_url: {
                  url: imageBase64
                }
              }
            ]
          }
        ],
        modalities: ['image', 'text']
      })
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('Lovable AI error:', response.status, errorText);
      
      if (response.status === 429) {
        throw new Error('Rate limit exceeded. Please try again in a moment.');
      }
      if (response.status === 402) {
        throw new Error('AI credits exhausted. Please add credits to continue.');
      }
      
      throw new Error(`AI service error: ${response.status} - ${errorText}`);
    }

    const result = await response.json();
    console.log('Lovable AI response received');

    // Extract the generated image from the response
    const editedImageUrl = result.choices?.[0]?.message?.images?.[0]?.image_url?.url;
    
    if (editedImageUrl) {
      return new Response(
        JSON.stringify({ 
          success: true, 
          editedImage: editedImageUrl,
          message: 'Photo edited successfully'
        }),
        { 
          headers: { ...corsHeaders, 'Content-Type': 'application/json' },
          status: 200 
        }
      );
    }

    // If no image found in response, return error
    console.error('No image data found in AI response:', JSON.stringify(result));
    throw new Error('No image generated by AI');

  } catch (error) {
    console.error('Error in edit-passport-photo function:', error);
    return new Response(
      JSON.stringify({ 
        error: error instanceof Error ? error.message : 'Unknown error occurred',
        details: 'Failed to process image with AI'
      }),
      { 
        status: 500, 
        headers: { ...corsHeaders, 'Content-Type': 'application/json' } 
      }
    );
  }
});
